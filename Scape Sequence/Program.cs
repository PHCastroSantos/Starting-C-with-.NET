//It is a way to format the text for the user.
/*
\a -> Bell (alert)
\b -> Backspace
\f -> Form feed
\n -> New line
\r -> Carriage return
\t -> Horizontal tab
\v -> Vertical tab
\' -> Single quotation mark
\" -> Double quotation mark
\\ -> Backslash
\? -> Literal question mark
*/

//Example:
Console.WriteLine("Olá, \nmundo!");