void singHappyBirthday(String name, int age)
{
    System.Console.WriteLine("Happy birthday to you!");
    System.Console.WriteLine("Happy birthday to you!");
    System.Console.WriteLine("Happy birthday dear " + name);
    System.Console.WriteLine("You are " + age + " years old!");
